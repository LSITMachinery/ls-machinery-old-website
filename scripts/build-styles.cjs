/* Deterministic local CSS build; no package installation required. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'styles/manifest.json'), 'utf8'));
if (new Set(manifest).size !== manifest.length) throw new Error('Duplicate style source in manifest');
const sections = manifest.map(file => {
  const absolute = path.resolve(root, file);
  if (!absolute.startsWith(root + path.sep)) throw new Error('Style source outside workspace');
  const css = fs.readFileSync(absolute, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trim();
  if (file !== 'styles/tokens.css' && /:root\s*\{/.test(css)) throw new Error('Shared tokens belong in styles/tokens.css: ' + file);
  if (/@import\b/.test(css)) throw new Error('List style sources in styles/manifest.json instead of @import');
  return `/* Source: ${file} */\n${css}`;
});
const digest = crypto.createHash('sha256').update(sections.join('\n\n')).digest('hex').slice(0, 16);
const output = `/* Generated by node scripts/build-styles.cjs. Edit source files from styles/manifest.json.\n * Build: ${digest}\n */\n\n${sections.join('\n\n')}\n`;
const destination = path.join(root, 'site.css');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
    console.error('site.css is out of date. Run node scripts/build-styles.cjs');
    process.exit(1);
  }
  console.log('site.css matches all source styles');
} else {
  fs.writeFileSync(destination, output);
  console.log(`Built site.css from ${manifest.length} sources (${Buffer.byteLength(output)} bytes)`);
}
